using UnityEngine;

#if UNITY_EDITOR
using UnityEditor;
using UnityEditor.SceneManagement;
#endif

public class GridBoardBuilder : MonoBehaviour
{
    [Header("Grid")]
    [Min(1)] public int rows = 10;
    [Min(1)] public int columns = 10;
    [Min(0.01f)] public float cellSize = 0.1f;

    [Header("Appearance")]
    [Min(0.001f)] public float lineWidth = 0.003f;
    public Material surfaceMaterial;
    public Material lineMaterial;

    [ContextMenu("Build Grid")]
    private void BuildGrid()
    {
#if UNITY_EDITOR
        if (Application.isPlaying)
        {
            Debug.LogWarning("Exit Play mode before building the grid.", this);
            return;
        }

        if (surfaceMaterial == null || lineMaterial == null)
        {
            Debug.LogError("Assign both grid materials first.", this);
            return;
        }

        if (rows < 1 || columns < 1 || cellSize <= 0f ||
            lineWidth <= 0f || lineWidth >= cellSize)
        {
            Debug.LogError("Check grid dimensions and line width.", this);
            return;
        }

        Undo.IncrementCurrentGroup();
        int undoGroup = Undo.GetCurrentGroup();
        Undo.SetCurrentGroupName("Build Grid");

        // Only replace objects generated by this component.
        Transform previous = transform.Find("GeneratedGrid");

        if (previous != null)
            Undo.DestroyObjectImmediate(previous.gameObject);

        GameObject generated = new GameObject("GeneratedGrid");
        generated.transform.SetParent(transform, false);
        Undo.RegisterCreatedObjectUndo(generated, "Create grid root");

        float width = columns * cellSize;
        float depth = rows * cellSize;

        // The top of the surface is at local Y = 0.
        CreateBlock(
            "Surface",
            generated.transform,
            new Vector3(0f, -0.01f, 0f),
            new Vector3(width, 0.02f, depth),
            surfaceMaterial,
            true
        );

        for (int column = 0; column <= columns; column++)
        {
            float x = -width * 0.5f + column * cellSize;

            CreateBlock(
                "ColumnLine_" + column,
                generated.transform,
                new Vector3(x, 0.0015f, 0f),
                new Vector3(lineWidth, 0.003f, depth),
                lineMaterial,
                false
            );
        }

        for (int row = 0; row <= rows; row++)
        {
            float z = -depth * 0.5f + row * cellSize;

            CreateBlock(
                "RowLine_" + row,
                generated.transform,
                new Vector3(0f, 0.0015f, z),
                new Vector3(width, 0.003f, lineWidth),
                lineMaterial,
                false
            );
        }

        Undo.CollapseUndoOperations(undoGroup);
        EditorSceneManager.MarkSceneDirty(gameObject.scene);

        Debug.Log(
            $"Built {rows}x{columns} grid, size {width:F2}m x {depth:F2}m.",
            this
        );
#endif
    }

#if UNITY_EDITOR
    private void CreateBlock(
        string objectName,
        Transform parent,
        Vector3 localPosition,
        Vector3 localScale,
        Material material,
        bool keepCollider)
    {
        GameObject block = GameObject.CreatePrimitive(PrimitiveType.Cube);
        block.name = objectName;

        block.transform.SetParent(parent, false);
        block.transform.localPosition = localPosition;
        block.transform.localRotation = Quaternion.identity;
        block.transform.localScale = localScale;

        block.GetComponent<MeshRenderer>().sharedMaterial = material;

        if (!keepCollider)
            DestroyImmediate(block.GetComponent<BoxCollider>());

        Undo.RegisterCreatedObjectUndo(block, "Create grid part");
    }
#endif
}